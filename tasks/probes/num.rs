fn main() {
    let a: i32 = -17;
    let b: u64 = 1 << 40;
    println!("{} {} {}", a.abs(), a.pow(2), a.signum());
    println!("{} {}", a / 5, a % 5);
    println!("{} {}", a.rem_euclid(5), a.div_euclid(5));
    println!("{} {}", b.count_ones(), b.trailing_zeros());
    println!("{} {}", b.leading_zeros(), (b as f64).sqrt());
    println!("{:?} {:?}", 200u8.checked_add(100), 200u8.checked_add(10));
    println!("{} {}", 250u8.wrapping_add(10), 250u8.saturating_add(10));
    println!("{}", i32::MAX.wrapping_add(1));
    println!("{:?}", 5i32.checked_div(0));
    println!("{} {}", 7.max(3), 7.min(3));
    println!("{}", 15.clamp(0, 10));
    let x = 2.5f64;
    println!("{} {} {} {}", x.floor(), x.ceil(), x.round(), x.trunc());
    println!("{} {:.3}", x.powi(3), x.powf(0.5));
    println!("{:.4} {:.4} {:.4}", x.sin(), x.ln(), x.exp());
    println!("{} {}", f64::MAX > 1e300, f64::NAN.is_nan());
    println!("{} {}", x.max(3.0), x.min(1.0));
    println!("{}", (x as i32) + (3.99f64 as i32));
    println!("{}", (-1i32) as u32);
    println!("{}", 300i32 as u8);
    println!("{}", 65u8 as char);
    println!("{}", 'A' as u32 + 1);
    println!("{}", u8::try_from(300i32).is_err());
    let big: i64 = i64::from(a) * 1_000_000_000;
    println!("{}", big);
    println!("{}", usize::MAX > 0);
    println!("{}", (10u32).pow(9));
    println!("{}", 17 / 3 * 3);
    println!("{:?}", 10.0f64.partial_cmp(&3.0));
    println!("{}", 1e-7);
    println!("{}", 0.1 + 0.2);
    println!("{}", 100.0f64 / 3.0);
    println!("{}", (2.0f64).hypot(3.0) > 3.6);
    println!("{}", 12u32.is_power_of_two());
    println!("{}", 37i64.abs_diff(50));
    println!("{}", i32::from_str_radix("ff", 16).unwrap());
    println!("{:?}", char::from_digit(7, 10));
    println!("{:?}", '9'.to_digit(10));
    println!("{}", std::cmp::max(3, 9));
    println!("{}", f64::from(3i32) / 2.0);
    let total: f64 = vec![1.5, 2.5].iter().sum();
    println!("{}", total);
    let avg = total / 2 as f64;
    println!("{}", avg);
    println!("{}", u64::MAX);
    println!("{}", i64::MIN);
    println!("{}", (u32::MAX as u64) + 1);
}
