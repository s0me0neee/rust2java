fn main() {
    let s = String::from("Hello, World");
    let t = "  padded\t";
    println!("{} {} {}", s.to_lowercase(), s.to_uppercase(), t.trim());
    println!("{} {}", t.trim_start(), t.trim_end().len());
    println!("{:?} {:?}", s.find(','), s.rfind('o'));
    println!("{:?}", s.split_once(", "));
    println!("{}", s.replace("l", "L"));
    println!("{}", s.replacen('l', "_", 2));
    println!("{} {}", s.starts_with("Hell"), s.ends_with('d'));
    println!("{:?}", s.strip_prefix("Hello").map(|r| r.trim()));
    println!("{:?}", s.strip_suffix("World"));
    println!("{}", &s[7..]);
    println!("{}", &s[..5]);
    println!("{:?}", s.chars().rev().collect::<String>());
    println!("{:?}", s.char_indices().filter(|(_, c)| c.is_uppercase()).map(|(i, _)| i).collect::<Vec<_>>());
    let mut b = String::with_capacity(10);
    b.push_str("ab");
    b.push('c');
    b.insert(0, 'z');
    b.insert_str(1, "yy");
    let popped = b.pop();
    println!("{} {:?}", b, popped);
    b.truncate(2);
    println!("{} {}", b, b.is_empty());
    b.clear();
    println!("[{}]", b);
    let words: Vec<&str> = "a,b,,c".split(',').collect();
    println!("{:?}", words);
    let parts: Vec<String> = "x y  z".split_whitespace().map(String::from).collect();
    println!("{}", parts.join("-"));
    println!("{}", "ab".repeat(3));
    println!("{:?}", "abc".as_bytes());
    println!("{:?}", "line1\nline2\n".lines().collect::<Vec<_>>());
    println!("{}", "42".parse::<i32>().unwrap() + 1);
    println!("{:?}", "x".parse::<i32>().is_err());
    println!("{:?}", "3.5".parse::<f64>());
    let c = s.chars().nth(4).unwrap();
    println!("{} {}", c, s.chars().count());
    println!("{}", s.contains("World") && !s.contains('z'));
    println!("{:?}", s.bytes().map(|b| b as u32).sum::<u32>());
    let num = 255;
    println!("{}", num.to_string() + "!");
    println!("{}", format!("{}{}", "a", 1) == "a1");
    println!("{:?}", "b".cmp("a"));
    println!("{}", "Abc".eq_ignore_ascii_case("aBC"));
    println!("{:?}", "a-b_c".split(|c: char| c == '-' || c == '_').collect::<Vec<_>>());
    println!("{:?}", "hello".char_indices().nth(1));
    println!("{}", String::from_utf8(vec![104, 105]).unwrap());
    println!("{}", "tEst".to_ascii_uppercase());
    let owned: String = 'x'.into();
    println!("{}", owned + &"y".to_string());
    println!("{:?}", "a=1;b=2".split(';').map(|kv| kv.split('=').collect::<Vec<_>>()).collect::<Vec<_>>());
    println!("{}", "abc" < "abd");
    println!("{}", s.get(0..5).unwrap_or(""));
    println!("{:?}", "rust".chars().position(|c| c == 's'));
}
